/** JSONB may reorder object keys; array order and every value remain significant. */
export function canonicalKnowledgeValue(value: unknown): string {
  return JSON.stringify(value, (_key, item) =>
    item && typeof item === "object" && !Array.isArray(item)
      ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a.localeCompare(b)))
      : item,
  );
}

export async function basisFingerprint(value: unknown) {
  const bytes = new TextEncoder().encode(canonicalKnowledgeValue(value));
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
}
