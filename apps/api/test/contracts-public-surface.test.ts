describe("explicit package public surfaces", () => {
  it.each([
    ["core", core, coreValues],
    ["shared", shared, sharedValues],
  ] as const)("retains every runtime export of %s", (_name, namespace, expected) => {
    expect(Object.keys(namespace).sort()).toEqual(expected);
    for (const key of expected) expect(Reflect.get(namespace, key)).toBeDefined();
  });

  it("retains type exports and does not publish a newly added internal export", () => {
    const roots = ["core", "shared"].map((name) =>
      fileURLToPath(new URL(`../../../packages/${name}/src/index.ts`, import.meta.url)),
    );
    const options: ts.CompilerOptions = {
      target: ts.ScriptTarget.ESNext,
      module: ts.ModuleKind.NodeNext,
      moduleResolution: ts.ModuleResolutionKind.NodeNext,
      skipLibCheck: true,
      noEmit: true,
    };
    const host = ts.createCompilerHost(options);
    const read = host.readFile.bind(host);
    host.readFile = (file) => {
      const source = read(file);
      if (source === undefined) return source;
      // Simulate a developer adding a value AND a type to existing modules.
      return /packages\/(core|shared)\/src\/(model|records)\.ts$/.test(file)
        ? `${source}\nexport const InternalContractProbe = 1;\nexport type InternalTypeProbe = string;`
        : source;
    };
    const program = ts.createProgram(roots, options, host);
    const checker = program.getTypeChecker();
    for (const [i, names] of [coreNames, sharedNames].entries()) {
      const root = program.getSourceFile(roots[i])!;
      const exported = checker.getExportsOfModule(checker.getSymbolAtLocation(root)!);
      expect(exported.map((symbol) => symbol.name).sort()).toEqual(names);
      expect(readFileSync(roots[i], "utf8")).not.toMatch(/export\s+(?:type\s+)?\*/);
      // Ensure the synthetic internal exports really exist in the compiler.
      const implementation = program.getSourceFile(
        roots[i].replace("index.ts", i === 0 ? "model.ts" : "records.ts"),
      )!;
      expect(
        checker
          .getExportsOfModule(checker.getSymbolAtLocation(implementation)!)
          .map((symbol) => symbol.name),
      ).toEqual(expect.arrayContaining(["InternalContractProbe", "InternalTypeProbe"]));
    }
  });
});
